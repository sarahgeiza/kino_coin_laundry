BEGIN;

CREATE TABLE IF NOT EXISTS pelanggan (
    id_pelanggan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- kode_pelanggan dipakai untuk token QR Code
    kode_pelanggan VARCHAR(20) NOT NULL UNIQUE, 
    nama_pelanggan VARCHAR(100) NOT NULL,
    no_hp VARCHAR(20) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pesanan (
    id_pesanan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pelanggan BIGINT NOT NULL
        -- Diganti RESTRICT agar riwayat kasir/laporan shift tidak hilang
        REFERENCES pelanggan (id_pelanggan) ON DELETE RESTRICT, 
    layanan VARCHAR(50) NOT NULL,
    
    -- Menambahkan pencatatan berat cucian dengan batas max 7.5 kg
    berat_kg NUMERIC(4,2) NOT NULL 
        CHECK (berat_kg > 0 AND berat_kg <= 7.50),
        
    jumlah INTEGER NOT NULL DEFAULT 1 CHECK (jumlah BETWEEN 1 AND 50),
    total INTEGER NOT NULL DEFAULT 0 CHECK (total >= 0),
    catatan VARCHAR(255),
    status VARCHAR(10) NOT NULL DEFAULT 'Proses'
        CHECK (status IN ('Proses', 'Selesai', 'Diambil')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_pesanan_pelanggan
    ON pesanan (id_pelanggan);
CREATE INDEX IF NOT EXISTS idx_pesanan_created_at
    ON pesanan (created_at);
CREATE INDEX IF NOT EXISTS idx_pesanan_status
    ON pesanan (status);

COMMIT;
